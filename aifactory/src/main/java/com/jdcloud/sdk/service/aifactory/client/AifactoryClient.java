    public interface Builder {
        public Builder credentialsProvider(CredentialsProvider provider);
        public Builder environment(Environment environment);
        public Builder httpRequestConfig(HttpRequestConfig config);
        public AifactoryClient build() throws JdcloudSdkException;
    }

    private static class DefaultBuilder implements Builder {

        private AifactoryClient aifactoryClient;

        public DefaultBuilder() {
            aifactoryClient = new AifactoryClient();
        }

        public DefaultBuilder credentialsProvider(CredentialsProvider provider) {
            aifactoryClient.credentialsProvider = provider;
            return this;
        }

        public DefaultBuilder httpRequestConfig(HttpRequestConfig config) {
            aifactoryClient.httpRequestConfig = config;
            return this;
        }

        public AifactoryClient build() throws JdcloudSdkException {

            if (aifactoryClient.credentialsProvider == null) {
                //if credentialsProvider not set, try load jdcloud global default  credentials provider
                aifactoryClient.credentialsProvider = Jdcloud.defaultInstance().getCredentialsProvider();
                if (aifactoryClient.credentialsProvider == null) {
                    throw new JdcloudValidateException("AifactoryClient build error: jdcloud credentials provider not set");
                }
            }
            if (aifactoryClient.httpRequestConfig == null) {
                aifactoryClient.httpRequestConfig = Jdcloud.defaultInstance().getHttpRequestConfig();
                if (aifactoryClient.httpRequestConfig == null) {
                    throw new JdcloudValidateException("AifactoryClient build error: http request config not set");
                }
            }
            return aifactoryClient;
        }

        public Builder environment(Environment environment) {
            aifactoryClient.environment = environment;
            return this;
        }
    }
