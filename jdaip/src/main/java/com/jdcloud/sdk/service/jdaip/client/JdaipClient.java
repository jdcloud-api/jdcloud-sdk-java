    public interface Builder {
        public Builder credentialsProvider(CredentialsProvider provider);
        public Builder environment(Environment environment);
        public Builder httpRequestConfig(HttpRequestConfig config);
        public JdaipClient build() throws JdcloudSdkException;
    }

    private static class DefaultBuilder implements Builder {

        private JdaipClient jdaipClient;

        public DefaultBuilder() {
            jdaipClient = new JdaipClient();
        }

        public DefaultBuilder credentialsProvider(CredentialsProvider provider) {
            jdaipClient.credentialsProvider = provider;
            return this;
        }

        public DefaultBuilder httpRequestConfig(HttpRequestConfig config) {
            jdaipClient.httpRequestConfig = config;
            return this;
        }

        public JdaipClient build() throws JdcloudSdkException {

            if (jdaipClient.credentialsProvider == null) {
                //if credentialsProvider not set, try load jdcloud global default  credentials provider
                jdaipClient.credentialsProvider = Jdcloud.defaultInstance().getCredentialsProvider();
                if (jdaipClient.credentialsProvider == null) {
                    throw new JdcloudValidateException("JdaipClient build error: jdcloud credentials provider not set");
                }
            }
            if (jdaipClient.httpRequestConfig == null) {
                jdaipClient.httpRequestConfig = Jdcloud.defaultInstance().getHttpRequestConfig();
                if (jdaipClient.httpRequestConfig == null) {
                    throw new JdcloudValidateException("JdaipClient build error: http request config not set");
                }
            }
            return jdaipClient;
        }

        public Builder environment(Environment environment) {
            jdaipClient.environment = environment;
            return this;
        }
    }
